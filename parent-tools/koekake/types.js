/**
 * タイプを判定する。answers は { q1: "a" | "b", ... , sensory: true/false }
 * 各軸で b が3つ以上なら b、1つ以下なら a、2つなら「どちらとも」として、
 * その軸の最初の質問の答えで決め、近いタイプも返す。
 */
export function diagnose(answers) {
  const axes = {};
  const balanced = [];
  for (const axis of ["approach", "intensity"]) {
    const qs = TYPE_QUESTIONS.filter((q) => q.axis === axis);
    const bCount = qs.filter((q) => answers[q.id] === "b").length;
    if (bCount >= 3) axes[axis] = "b";
    else if (bCount <= 1) axes[axis] = "a";
    else {
      axes[axis] = answers[qs[0].id] === "b" ? "b" : "a";
      balanced.push(axis);
    }
  }
  const type = TYPES.find((t) => t.axes.approach === axes.approach && t.axes.intensity === axes.intensity);
  const near = balanced.map((axis) => {
    const flipped = { ...axes, [axis]: axes[axis] === "a" ? "b" : "a" };
    return TYPES.find((t) => t.axes.approach === flipped.approach && t.axes.intensity === flipped.intensity);
  });
  return { type, near, sensory: answers.sensory === true };
}

export function isComplete(answers) {
  return TYPE_QUESTIONS.every((q) => answers[q.id] === "a" || answers[q.id] === "b");
}
